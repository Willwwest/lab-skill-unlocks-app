// Writes supabase/seed.sql from the prototype's own demo data, so the
// database starts with exactly what the app shows today.
//
//   node scripts/build-seed.mjs            (from app/)
//
// Ids are deterministic (md5 of kind + legacy id), so re-running gives the
// same uuids and seed.sql diffs stay readable. Catalog, schedule and layout
// are real configuration; staff, families, kids and their records are
// marked is_demo and can be removed with private.purge_demo_data().
import { createHash } from "node:crypto";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { catalog, tiers, bonuses, people, seed } from "../src/domain.js";
import { staff, families, kidInfo } from "../src/roster.js";
import {
  stations,
  shoutouts,
  prizes,
  groups,
  points,
  sessions,
} from "../src/club.js";
import { defaultLayout, BUILDING } from "../src/layout.js";
import { seedGym, stationFocus } from "../src/gym.js";
import { crewFor } from "../src/gym.js";
import { seedStaffing } from "../src/staffing.js";
import { stationCategory } from "../src/floor.js";
import { plain } from "../src/skillcopy.js";

const now = new Date();
const today = now.toISOString().slice(0, 10);

const uuid = (kind, id) => {
  const h = createHash("md5").update(`lab:${kind}:${id}`).digest("hex");
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-4${h.slice(13, 16)}-a${h.slice(17, 20)}-${h.slice(20, 32)}`;
};
const q = (v) =>
  v === null || v === undefined
    ? "null"
    : typeof v === "number" || typeof v === "boolean"
      ? String(v)
      : `'${String(v).replace(/'/g, "''")}'`;
const arr = (list, type = "text") =>
  `array[${list.map(q).join(", ")}]::${type}[]`;
const json = (v) => `${q(JSON.stringify(v))}::jsonb`;
const out = [];
const insert = (table, rows) => {
  if (!rows.length) return;
  const cols = Object.keys(rows[0]);
  out.push(
    `insert into public.${table} (${cols.join(", ")}) values\n` +
      rows
        .map((r) => `  (${cols.map((c) => r[c] ?? "null").join(", ")})`)
        .join(",\n") +
      ";\n",
  );
};

const ORG = uuid("org", "the-lab");
const LOC = uuid("location", "pilot");
const staffId = (id) => uuid("staff", id);
const staffByName = (name) => staff.find((s) => s.name === name);
const kidId = (id) => uuid("athlete", id);
const skillId = (code) => uuid("skill", code);
const stationId = (code) => uuid("station", code);
const blockId = (i) => uuid("block", i);

out.push(`-- Generated by app/scripts/build-seed.mjs. Do not edit; rerun it.
select set_config('app.skip_audit', 'on', false);
`);

insert("orgs", [
  { id: q(ORG), slug: q("the-lab"), name: q("The LAB"), demo_mode: "true" },
]);
insert("locations", [
  {
    id: q(LOC),
    org_id: q(ORG),
    slug: q("pilot"),
    name: q("The LAB (pilot location)"),
    timezone: q("America/Phoenix"),
    building: json(BUILDING),
  },
]);

// Catalog -------------------------------------------------------------------
