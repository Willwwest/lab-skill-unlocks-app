// The prototype stores age and MM-DD; derive a birth year from them.
const birthdate = (age, mmdd) => {
  const [m, d] = mmdd.split("-").map(Number);
  const passed =
    now.getUTCMonth() + 1 > m ||
    (now.getUTCMonth() + 1 === m && now.getUTCDate() >= d);
  const year = now.getUTCFullYear() - age - (passed ? 0 : 1);
  return `${year}-${mmdd}`;
};
